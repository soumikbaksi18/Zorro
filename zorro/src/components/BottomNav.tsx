/** Reads the URL to highlight the current tab. Wrap in <Suspense> with <NavBar /> as fallback. */
export function BottomNav() {
  return <NavBar pathname={usePathname()} />;
}

/** The nav itself. With no pathname (while the URL streams in) no tab is highlighted. */
export function NavBar({ pathname }: { pathname?: string }) {
  return (
    <nav
      aria-label="Main"
      className="fixed inset-x-0 bottom-0 z-20 border-t border-line bg-ink/90 pb-[env(safe-area-inset-bottom)] backdrop-blur"
    >
      <ul className="mx-auto flex max-w-md">
        {TABS.map((tab) => {
          const active =
            pathname !== undefined &&
            (tab.href === "/"
              ? pathname === "/"
              : pathname.startsWith(tab.href) ||
                (tab.href === "/orders" && pathname.startsWith("/swap/")) ||
                (tab.href === "/trade" && pathname === "/swap"));
          return (
            <li key={tab.href} className="flex-1">
              <Link
                href={tab.href}
                aria-current={active ? "page" : undefined}
                className={`flex flex-col items-center gap-1 py-2.5 text-[11px] font-medium transition-colors ${
                  active ? "text-fox-light" : "text-muted hover:text-snow"
                }`}
              >
                <svg
                  viewBox="0 0 24 24"
                  className="h-6 w-6"
                  fill="none"
                  stroke="currentColor"
                  strokeWidth={1.8}
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  aria-hidden="true"
                >
                  {tab.icon}
                </svg>
                {tab.label}
              </Link>
            </li>
          );
        })}
      </ul>
    </nav>
  );
}
